export function presetByPath(pathname) {
  const path = pathname.length > 1 && pathname.endsWith('/')
    ? pathname.slice(0, -1)
    : pathname
  return presets.find((item) => item.path === path) || null
}

export function presetById(id) {
  return presets.find((item) => item.id === id) || null
}
