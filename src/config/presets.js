// Check every size against the latest official notification before launch.
// If the notice gives centimetres, pixels are that size at 200 DPI:
// px = round(cm / 2.54 * 200). If the notice gives pixels, those pixels are used.
// width and height are null on the KB-only presets: those keep the original
// aspect ratio and only compress the file.

const remind = ' लॉन्च से पहले नई सूचना से मिला लें।'

function tool(spec) {
  return {
    cmWidth: null,
    cmHeight: null,
    ...spec,
    sourceNote: `${spec.sourceNote}${remind}`,
  }
}

function both(exam, slug, photo, sign, photoNote, signNote) {
  return [
    tool({
      id: `${slug}-photo`,
      path: `/${slug}-photo-resize`,
      exam,
      type: 'photo',
      width: photo.w,
      height: photo.h,
      cmWidth: photo.cmW ?? null,
      cmHeight: photo.cmH ?? null,
      minKb: photo.min,
      maxKb: photo.max,
      labelHi: `${exam} फोटो`,
      labelEn: `${exam} Photo`,
      fileSlug: `${slug}-photo`,
      sourceNote: photoNote,
    }),
    tool({
      id: `${slug}-signature`,
      path: `/${slug}-signature-resize`,
      exam,
      type: 'signature',
      width: sign.w,
      height: sign.h,
      cmWidth: sign.cmW ?? null,
      cmHeight: sign.cmH ?? null,
      minKb: sign.min,
      maxKb: sign.max,
      labelHi: `${exam} सिग्नेचर`,
      labelEn: `${exam} Signature`,
      fileSlug: `${slug}-signature`,
      sourceNote: signNote,
    }),
  ]
}

